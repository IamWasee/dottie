    // MARK: - Visual Helpers

    /// The system popover material, rounded and outlined like a menu bar
    /// extra's panel.
    private var panelBackground: some View {
        let panelOutline = RoundedRectangle(cornerRadius: 12, style: .continuous)
        return DSVisualEffectBackground(material: .popover, state: .active)
            .clipShape(panelOutline)
            .overlay(panelOutline.stroke(DS.Colors.borderSubtle, lineWidth: 0.5))
    }

    private var statusDotColor: Color {
        if !companionManager.isOverlayVisible {
            return DS.Colors.textTertiary
        }
        switch companionManager.voiceState {
        case .idle:
            return DS.Colors.success
        case .listening:
            return DS.Colors.blue400
        case .processing, .responding:
            return DS.Colors.blue400
        }
    }

    private var statusText: String {
        if !companionManager.hasCompletedOnboarding || !companionManager.allPermissionsGranted {
            return "Setup"
        }
        if !companionManager.isOverlayVisible {
            return "Ready"
        }
        switch companionManager.voiceState {
        case .idle:
            return "Active"
        case .listening:
            return "Listening"
        case .processing:
            return "Processing"
        case .responding:
            return "Responding"
        }
    }

}

/// Plays (or stops) a sample of the chosen voice in the panel.
private struct VoicePreviewButton: View {
    let voiceName: String
    @ObservedObject private var voicePreview = DottieVoicePreview.shared

    var body: some View {
        Button(action: { voicePreview.toggle(voiceName) }) {
            Group {
                if voicePreview.loadingVoiceName == voiceName {
                    ProgressView().controlSize(.mini)
                } else {
                    Image(systemName: voicePreview.playingVoiceName == voiceName ? "stop.fill" : "speaker.wave.2.fill")
                        .font(.system(size: 10))
                        .foregroundColor(DS.Colors.textSecondary)
                }
            }
            .frame(width: 22, height: 22)
        }
        .buttonStyle(.plain)
        .pointerCursor()
        .padding(.leading, 6)
        .help("Hear \(voiceName)")
    }
}
